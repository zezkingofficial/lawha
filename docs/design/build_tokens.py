#!/usr/bin/env python3
"""Generate tokens.css and tailwind.tokens.js from tokens.json + tokens-dark.json.

    python3 build_tokens.py            # writes next to this file

Components use Tailwind classes like bg-surface text-muted, never raw hex.
Re-run after any token change (including the rebrand), then run contrast.py.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
light = json.load(open(os.path.join(HERE, "tokens.json"), encoding="utf-8"))
dark = json.load(open(os.path.join(HERE, "tokens-dark.json"), encoding="utf-8"))


def color_vars(colors):
    return "\n".join(f"  --c-{k}: {v};" for k, v in colors.items())


css = [
    "/* Generated by build_tokens.py from tokens.json. Do not edit by hand. */",
    "@import url('https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Arabic:wght@400;500;600;700&family=IBM+Plex+Sans:wght@400;500;600;700&display=swap');",
    "",
    ":root {",
    color_vars(light["color"]),
    f"  --font-sans: {light['font']['sans']};",
    f"  --font-mono: {light['font']['mono']};",
]
for name, t in light["type"].items():
    css.append(f"  --text-{name}: {t['size']}px; --leading-{name}: {t['line']}px; --weight-{name}: {t['weight']};")
for i, s in enumerate(light["space"]):
    css.append(f"  --space-{i}: {s}px;")
for k, v in light["radius"].items():
    css.append(f"  --radius-{k}: {v}px;")
for k, v in light["shadow"].items():
    css.append(f"  --shadow-{k}: {v};")
for k, v in light["motion"].items():
    css.append(f"  --motion-{k}: {v};")
for k, v in light["layout"].items():
    if isinstance(v, (int, float)):
        css.append(f"  --{k}: {v}px;")
css.append("  color-scheme: light;")
css.append("}")
css.append("")
dark_block = color_vars(dark["color"]) + "\n  color-scheme: dark;"
css += [
    "@media (prefers-color-scheme: dark) {",
    "  :root:not([data-theme=\"light\"]) {",
    "  " + dark_block.replace("\n", "\n  "),
    "  }",
    "}",
    ":root[data-theme=\"dark\"] {",
    dark_block,
    "}",
    "",
    "html { font-family: var(--font-sans); font-size: var(--text-base); line-height: var(--leading-base); }",
    "body { background: var(--c-bg); color: var(--c-text); }",
    ":focus-visible { outline: 2px solid var(--c-focus); outline-offset: 2px; }",
    "@media (prefers-reduced-motion: reduce) { *, *::before, *::after { transition-duration: 0ms !important; animation-duration: 0ms !important; } }",
]
open(os.path.join(HERE, "tokens.css"), "w", encoding="utf-8").write("\n".join(css) + "\n")

tw_colors = {k: f"var(--c-{k})" for k in light["color"]}
tw = {
    "darkMode": ["selector", "[data-theme=\"dark\"]"],
    "theme": {
        "extend": {
            "colors": tw_colors,
            "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
            "fontSize": {n: [f"{t['size']}px", {"lineHeight": f"{t['line']}px", "fontWeight": str(t["weight"])}]
                         for n, t in light["type"].items()},
            # spacing: Tailwind's default 4px scale is the token scale (1=4px, 2=8px, 3=12px ...), so it is not overridden
            "borderRadius": {k: f"{v}px" for k, v in light["radius"].items()},
            "boxShadow": light["shadow"],
            "transitionDuration": {k: v for k, v in light["motion"].items() if k != "ease"},
            "transitionTimingFunction": {"brand": light["motion"]["ease"]},
            "height": {"row": "36px", "row-compact": "32px", "topbar": "48px", "group": "40px"},
            "width": {"sidebar": "256px", "sidebar-collapsed": "56px", "name-col": "320px", "panel": "560px"},
        }
    },
}
js = ("// Generated by build_tokens.py from tokens.json. Do not edit by hand.\n"
      "// Spread into tailwind.config: module.exports = { ...require('./tailwind.tokens'), content: [...] }\n"
      "module.exports = " + json.dumps(tw, indent=2, ensure_ascii=False) + ";\n")
open(os.path.join(HERE, "tailwind.tokens.js"), "w", encoding="utf-8").write(js)
print("wrote tokens.css and tailwind.tokens.js")
